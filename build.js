/**
 * Bundles the only part of the extension that needs third-party libraries.
 *
 * DOCX and PDF generation depend on `docx` and `pdfmake`; every other script
 * ships as plain source the browser loads directly. Rather than putting the
 * whole extension behind a bundler, just this one entry point is compiled.
 *
 * The output is committed to vendor/ so cloning the repo and loading it
 * unpacked needs no npm install. Rebuild with `npm run build` after changing
 * pro/formats/documents.src.js.
 *
 * @license MIT
 */
'use strict';

const esbuild = require('esbuild');
const fs = require('fs');
const path = require('path');

const ENTRY = 'pro/formats/documents.src.js';
const OUTFILE = 'vendor/pro-documents.bundle.js';

async function main() {
  const watch = process.argv.includes('--watch');

  const options = {
    entryPoints: [ENTRY],
    outfile: OUTFILE,
    bundle: true,
    minify: !process.argv.includes('--dev'),
    sourcemap: false,
    // Content scripts cannot be ES modules, so emit a classic script. The
    // bundle registers itself on globalThis.AISE, matching every other file.
    format: 'iife',
    platform: 'browser',
    target: ['chrome110'],
    legalComments: 'none',
    banner: {
      js:
        '/* AI Studio Exporter - bundled DOCX/PDF support.\n' +
        ' * Generated by build.js from ' + ENTRY + ' - do not edit by hand.\n' +
        ' * Bundles docx (MIT) and pdfmake (MIT). See THIRD-PARTY.md.\n' +
        ' */',
    },
  };

  if (watch) {
    const ctx = await esbuild.context(options);
    await ctx.watch();
    console.log(`watching ${ENTRY} -> ${OUTFILE}`);
    return;
  }

  const start = Date.now();
  await esbuild.build(options);

  const bytes = fs.statSync(OUTFILE).size;
  console.log(
    `built ${OUTFILE} in ${Date.now() - start}ms (${(bytes / 1024 / 1024).toFixed(2)} MB)`
  );

  // The bundle is loaded as a content script, so anything it pulls in that
  // needs eval or a remote fetch would be blocked by the extension CSP at
  // runtime. Fail the build here instead of discovering it in the browser.
  const source = fs.readFileSync(OUTFILE, 'utf8');

  // Bundled dependencies ship a few dynamic-code constructs that are never
  // reached in this environment. Rather than failing on every match, or
  // ignoring the category entirely, subtract the ones whose unreachability has
  // been checked so that anything new stands out.
  const KNOWN_UNREACHABLE = [
    {
      // globalThis polyfill. The fallback runs only when globalThis is absent,
      // and the build targets Chrome 110+ where it always exists.
      pattern: /new Function\("return this"\)/g,
      why: 'globalThis polyfill fallback',
    },
    {
      // setImmediate shim, which stringifies its argument only when handed a
      // non-function. pdfmake always passes a function.
      pattern: /new Function\(""\+\w+\)/g,
      why: 'setImmediate shim for non-function arguments',
    },
  ];

  const count = (pattern) => (source.match(pattern) || []).length;
  const totals = {
    'new Function()': count(/new Function\s*\(/g),
    'eval()': count(/[^.\w]eval\s*\(/g),
    'importScripts()': count(/\bimportScripts\s*\(/g),
  };

  let unexplained = totals['new Function()'];
  for (const { pattern, why } of KNOWN_UNREACHABLE) {
    const n = count(pattern);
    if (n) console.log(`  ignoring ${n} x new Function() - ${why}`);
    unexplained -= n;
  }

  const problems = [];
  if (unexplained > 0) problems.push(`${unexplained} unexplained new Function()`);
  if (totals['eval()']) problems.push(`${totals['eval()']} eval()`);
  if (totals['importScripts()']) problems.push(`${totals['importScripts()']} importScripts()`);

  if (problems.length) {
    console.error(
      'Bundle contains dynamic-code constructs the extension CSP blocks: ' +
        problems.join(', ') +
        '\nInspect them and either remove the dependency or, once confirmed ' +
        'unreachable, add the pattern to KNOWN_UNREACHABLE in build.js.'
    );
    process.exit(1);
  }
  console.log('CSP check passed');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
